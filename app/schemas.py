from pydantic import BaseModel, Field       # BaseModel gives typed validation and JSON serialization for incoming and outgoing data    |    Field allows us to add validation rules and descriptions to each field like min max length and regex patterns

class QueryRequest(BaseModel):      # Incoming user question from the web UI - gets 422 error if question is missing or too short/long
    question: str = Field(..., min_length=10, max_length=500)


class SubQuery(BaseModel):      # One research dimension generated by the Planner
    axis: str = Field(..., description="Research axis name, e.g. Performance")
    query: str = Field(..., description="Search query for Tavily")


class PlannerOutput(BaseModel):     # Structured output from the Query Planner LLM call
    technology_a: str
    technology_b: str
    axes: list[str] = Field(..., min_length=2, max_length=6)        # avoid too many Tavily calls and too much data to process
    sub_queries: list[SubQuery] = Field(..., min_length=2, max_length=6)


class SearchResult(BaseModel):      # One result from Tavily or other search sources
    title: str
    url: str
    content: str
    published_date: str = ""
    trust_tier: int = Field(default=0, ge=0, le=4)      # 4 = most credible, 0 = least credible, Tavily uses 1-4, but we allow 0 for other sources that don't have a trust tier


class MatrixCell(BaseModel):        # One cell in the Architecture Trade-Off Matrix
    axis: str
    technology: str
    claim: str
    source_url: str = ""
    source_title: str = ""
    published_date: str = ""
    confidence: str = Field(default="M", pattern="^[HML]$")
    tag: str = Field(default="INFERENCE", pattern="^(FACT|INFERENCE|UNVERIFIED)$")


class ConflictBadge(BaseModel):     # Flagged when two credible sources disagree on an axis
    axis: str
    description: str        # short description of the disagreement
    source_a_url: str
    source_b_url: str


class TradeOffMatrix(BaseModel):        # The complete structured output of the agent
    technology_a: str
    technology_b: str
    cells: list[MatrixCell]
    conflicts: list[ConflictBadge] = []
    insufficient_data: list[str] = []           # axes where there was not enough credible data to make a claim


class TraceStep(BaseModel):      # One step in the visible execution trace
    timestamp: str
    step: str
    detail: str


class AgentResponse(BaseModel):     # Full response returned to the frontend
    matrix: TradeOffMatrix
    trace: list[TraceStep]
    total_sources: int
    latency_seconds: float      # measured from the time the user submits the question to the time the response is returned (by backend, not including network latency to the frontend)